struct InputChunks(NonNull<sys::mtmd_input_chunks>);

impl Drop for InputChunks {
    fn drop(&mut self) {
        unsafe { sys::mtmd_input_chunks_free(self.0.as_ptr()) }
    }
}

/// `llama_sampler *` that frees itself.
struct Sampler(NonNull<sys::llama_sampler>);

impl Drop for Sampler {
    fn drop(&mut self) {
        unsafe { sys::llama_sampler_free(self.0.as_ptr()) }
    }
}

/// Turn a null-check on a raw pointer into a `NonNull`, or a descriptive error.
fn non_null<T>(p: *mut T, what: &str) -> Result<NonNull<T>> {
    NonNull::new(p).ok_or_else(|| anyhow!("{what}"))
}

