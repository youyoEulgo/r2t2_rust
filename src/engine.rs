//! Safe, RAII-wrapped bindings around libllama + libmtmd.
//!
//! This mirrors the reference implementation in the Python project's
//! `r2t2_llama/native_ext.cpp`: same call order, same parameters, same
//! tokenizer usage. The point of the port is that results match the Python
//! route byte for byte, so the sequence below is deliberate rather than
//! stylistic.
//!
//! Everything llama.cpp returns is a raw pointer. Each one is owned by a
//! wrapper struct whose `Drop` releases it, so a failure part-way through
//! loading cannot leak.

use std::ffi::{CStr, CString};
use std::path::Path;
use std::ptr::NonNull;

use anyhow::{anyhow, bail, Context as _, Result};

/// Raw bindings generated by bindgen in `build.rs`.
///
/// The generated code is not ours to fix at the source, and this toolchain
/// reports `unnecessary_transmute` inside it. Allowing the lints here keeps
/// `cargo build` clean without touching vendored output.
#[allow(
    non_upper_case_globals,
    non_camel_case_types,
    non_snake_case,
    dead_code,
    unnecessary_transmutes,
    clippy::all
)]
pub mod sys {
    include!(concat!(env!("OUT_DIR"), "/bindings.rs"));
}

// --------------------------------------------------------------------------- //
// RAII wrappers
// --------------------------------------------------------------------------- //
//
// Each wrapper owns one llama.cpp pointer and frees it on drop.
//
// SAFETY (why these are `Send`/`Sync`): the pointers are opaque handle types
// from llama.cpp, not references into Rust data, so moving the wrapper between
// threads is fine as long as calls are not *concurrent*. `Engine::run` takes
// `&self` and mutates the shared context, so `Engine` is `Sync` only in the
// sense that its methods must be externally serialised -- which the server does
// with a mutex. Marking the wrappers `Send` (not `Sync`) keeps the guards
// honest: it permits moving the engine to another thread, while the server's
// mutex is what makes concurrent use safe.

/// `llama_model *` that frees itself.
struct Model(NonNull<sys::llama_model>);

// SAFETY: see the note above on the handle types.
unsafe impl Send for Model {}

impl Drop for Model {
    fn drop(&mut self) {
        unsafe { sys::llama_model_free(self.0.as_ptr()) }
    }
}

/// `llama_context *` that frees itself.
struct Context(NonNull<sys::llama_context>);

// SAFETY: see the note above on the handle types.
unsafe impl Send for Context {}

impl Drop for Context {
    fn drop(&mut self) {
        unsafe { sys::llama_free(self.0.as_ptr()) }
    }
}

/// `mtmd_context *` that frees itself.
struct Mtmd(NonNull<sys::mtmd_context>);

// SAFETY: see the note above on the handle types.
unsafe impl Send for Mtmd {}

impl Drop for Mtmd {
    fn drop(&mut self) {
        unsafe { sys::mtmd_free(self.0.as_ptr()) }
    }
}

